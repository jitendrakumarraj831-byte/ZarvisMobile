describe("the Sec-MS-GEC token, version 2", () => {
  it.each(REFERENCE)("is the upstream reference's token for Unix time %i", (unix, token) => {
    expect(secMsGecV2(unix * 1000, TRUSTED_CLIENT_TOKEN)).toBe(token);
  });

  it("is <16 hex>-<64 hex>, upper case", () => {
    expect(secMsGecV2(Date.now(), TRUSTED_CLIENT_TOKEN)).toMatch(/^[0-9A-F]{16}-[0-9A-F]{64}$/);
  });

  it("is constant inside a five-minute window and changes at its edge", () => {
    const start = 1_790_000_100 * 1000; // a multiple of 300 s
    expect((start / 1000) % 300).toBe(0);
    expect(secMsGecV2(start + 299_999, TRUSTED_CLIENT_TOKEN)).toBe(secMsGecV2(start, TRUSTED_CLIENT_TOKEN));
    expect(secMsGecV2(start + 300_000, TRUSTED_CLIENT_TOKEN)).not.toBe(secMsGecV2(start, TRUSTED_CLIENT_TOKEN));
    expect(secMsGecV2(start - 1, TRUSTED_CLIENT_TOKEN)).not.toBe(secMsGecV2(start, TRUSTED_CLIENT_TOKEN));
  });

  it("depends on the client token too", () => {
    expect(secMsGecV2(1_790_000_000_000, "A".repeat(32))).not.toBe(secMsGecV2(1_790_000_000_000, TRUSTED_CLIENT_TOKEN));
  });

  it("does not depend on the milliseconds", () => {
    expect(secMsGecV2(1_790_000_000_001, TRUSTED_CLIENT_TOKEN)).toBe(secMsGecV2(1_790_000_000_999, TRUSTED_CLIENT_TOKEN));
  });
});
