#!/usr/bin/env node
// Generates the Android app's icon set (android/core/core-ui/.../icons/ZarvisIcons.kt) from the website's icon sprite
// (web/index.html, <symbol id="i-…">), so both apps draw the same icons from one source. Each symbol becomes a lazily built
// Compose ImageVector with the website's stroke (2, round caps and joins). Circles, rectangles, lines and polylines are turned
// into path data, because ImageVector draws paths only.
//
//   node scripts/generate-android-icons.mjs          rewrite ZarvisIcons.kt
//   node scripts/generate-android-icons.mjs --check  exit 1 if it is out of date
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const sprite = readFileSync(join(root, "web", "index.html"), "utf8");
const target = join(root, "android", "core", "core-ui", "src", "main", "kotlin", "com", "zarvismobile", "core", "ui", "icons", "ZarvisIcons.kt");

const num = (value) => Number.parseFloat(value);
const fmt = (n) => String(Math.round(n * 1000) / 1000);
const attrs = (tag) => Object.fromEntries([...tag.matchAll(/([\w-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));

/** Path data for one SVG shape element. */
function toPath(name, a) {
  switch (name) {
    case "path":
      return a.d;
    case "circle":
    case "ellipse": {
      const cx = num(a.cx), cy = num(a.cy), rx = num(a.rx ?? a.r), ry = num(a.ry ?? a.r);
      return `M${fmt(cx - rx)} ${fmt(cy)}a${fmt(rx)} ${fmt(ry)} 0 1 0 ${fmt(2 * rx)} 0a${fmt(rx)} ${fmt(ry)} 0 1 0 ${fmt(-2 * rx)} 0Z`;
    }
    case "rect": {
      const x = num(a.x ?? 0), y = num(a.y ?? 0), w = num(a.width), h = num(a.height);
      const r = Math.min(num(a.rx ?? a.ry ?? 0), w / 2, h / 2);
      if (!r) return `M${fmt(x)} ${fmt(y)}h${fmt(w)}v${fmt(h)}h${fmt(-w)}Z`;
      return `M${fmt(x + r)} ${fmt(y)}h${fmt(w - 2 * r)}a${fmt(r)} ${fmt(r)} 0 0 1 ${fmt(r)} ${fmt(r)}v${fmt(h - 2 * r)}a${fmt(r)} ${fmt(r)} 0 0 1 ${fmt(-r)} ${fmt(r)}` +
        `h${fmt(-(w - 2 * r))}a${fmt(r)} ${fmt(r)} 0 0 1 ${fmt(-r)} ${fmt(-r)}v${fmt(-(h - 2 * r))}a${fmt(r)} ${fmt(r)} 0 0 1 ${fmt(r)} ${fmt(-r)}Z`;
    }
    case "line":
      return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`;
    case "polyline":
    case "polygon": {
      const points = a.points.trim().split(/[\s,]+/);
      let d = `M${points[0]} ${points[1]}`;
      for (let i = 2; i < points.length; i += 2) d += `L${points[i]} ${points[i + 1]}`;
      return name === "polygon" ? d + "Z" : d;
    }
    default:
      throw new Error("unsupported SVG element <" + name + ">");
  }
}

const pascal = (id) => id.replace(/^i-/, "").split("-").map((part) => part[0].toUpperCase() + part.slice(1)).join("");

const icons = [];
for (const [, id, body] of sprite.matchAll(/<symbol id="(i-[\w-]+)" viewBox="0 0 24 24">([\s\S]*?)<\/symbol>/g)) {
  const parts = [...body.matchAll(/<(path|circle|ellipse|rect|line|polyline|polygon)\b([^>]*)\/?>/g)].map(([, name, tag]) => {
    const a = attrs(tag);
    return { d: toPath(name, a), filled: a.fill === "currentColor" };
  });
  if (!parts.length) throw new Error(id + " has no shapes");
  icons.push({ id, name: pascal(id), parts });
}
if (icons.length < 60) throw new Error("only " + icons.length + " icons found in web/index.html");

const lines = icons.map(({ id, name, parts }) => {
  const args = parts.map((p) => `${p.filled ? "filled" : "line"}("${p.d}")`).join(", ");
  return `    /** \`#${id}\` */\n    val ${name}: ImageVector by lazy { icon("${name}", ${args}) }`;
});

const out = `package com.zarvismobile.core.ui.icons

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.StrokeCap
import androidx.compose.ui.graphics.StrokeJoin
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.addPathNodes
import androidx.compose.ui.unit.dp

// GENERATED by scripts/generate-android-icons.mjs from the website's icon sprite (web/index.html). Do not edit by hand:
// change the sprite and run the script. The drawings are Lucide icons (ISC), see THIRD_PARTY_NOTICES.md and LICENSES/ISC-lucide.txt.

/**
 * The ZARVIS icon set, the same drawings as the website. Outline icons on a 24dp grid with a 2dp round stroke, drawn in black so
 * \`Icon(tint = …)\` colours them like any Material icon.
 */
object ZarvisIcons {
${lines.join("\n\n")}

    /** Every icon by its website id (\`i-home\`, …). */
    val all: Map<String, ImageVector> by lazy {
        mapOf(
${icons.map(({ id, name }) => `            "${id}" to ${name},`).join("\n")}
        )
    }
}

private class Part(val pathData: String, val filled: Boolean)

private fun line(pathData: String) = Part(pathData, filled = false)

private fun filled(pathData: String) = Part(pathData, filled = true)

private fun icon(name: String, vararg parts: Part): ImageVector {
    val builder = ImageVector.Builder(name = "Zarvis.$name", defaultWidth = 24.dp, defaultHeight = 24.dp, viewportWidth = 24f, viewportHeight = 24f)
    for (part in parts) {
        if (part.filled) {
            builder.addPath(pathData = addPathNodes(part.pathData), fill = SolidColor(Color.Black))
        } else {
            builder.addPath(
                pathData = addPathNodes(part.pathData),
                stroke = SolidColor(Color.Black),
                strokeLineWidth = 2f,
                strokeLineCap = StrokeCap.Round,
                strokeLineJoin = StrokeJoin.Round,
            )
        }
    }
    return builder.build()
}
`;

let current = "";
try { current = readFileSync(target, "utf8"); } catch { /* first run */ }
if (process.argv.includes("--check")) {
  if (current !== out) {
    console.error("ZarvisIcons.kt is out of date: run node scripts/generate-android-icons.mjs");
    process.exit(1);
  }
  console.log(`ZarvisIcons.kt matches web/index.html (${icons.length} icons)`);
} else {
  writeFileSync(target, out);
  console.log(current === out ? "already up to date" : `ZarvisIcons.kt written (${icons.length} icons)`);
}
