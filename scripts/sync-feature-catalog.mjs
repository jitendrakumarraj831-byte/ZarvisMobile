#!/usr/bin/env node
// Copies shared/feature-catalog.json (the one capability catalogue for the website and the Android app) into
// web/feature-pages.js, between the BEGIN/END markers. The website has no build step, so the catalogue is embedded;
// web/tests/featureCatalog.test.js fails when the embedded copy and the shared file differ.
//
//   node scripts/sync-feature-catalog.mjs          rewrite the embedded copy
//   node scripts/sync-feature-catalog.mjs --check  exit 1 if it is out of date
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const sharedPath = join(root, "shared", "feature-catalog.json");
const webPath = join(root, "web", "feature-pages.js");
const BEGIN = "  /* BEGIN shared/feature-catalog.json: generated by scripts/sync-feature-catalog.mjs, edit the shared file instead. */\n";
const END = "  /* END shared/feature-catalog.json */\n";

const shared = JSON.parse(readFileSync(sharedPath, "utf8"));
const block = BEGIN + "  const SHARED_CATALOG = " + JSON.stringify(shared, null, 2).replace(/\n/g, "\n  ") + ";\n" + END;
const web = readFileSync(webPath, "utf8");
const start = web.indexOf(BEGIN);
const end = web.indexOf(END);
if (start < 0 || end < start) {
  console.error("web/feature-pages.js has no BEGIN/END markers for the shared catalogue");
  process.exit(2);
}
const next = web.slice(0, start) + block + web.slice(end + END.length);
if (process.argv.includes("--check")) {
  if (next !== web) {
    console.error("web/feature-pages.js is out of date: run node scripts/sync-feature-catalog.mjs");
    process.exit(1);
  }
  console.log("web/feature-pages.js matches shared/feature-catalog.json");
} else {
  writeFileSync(webPath, next);
  console.log(next === web ? "already up to date" : "web/feature-pages.js updated");
}
